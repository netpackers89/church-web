export function telegramText(language, key, values = {}) {
	const selected = messages[TELEGRAM_LANGUAGES.includes(language) ? language : 'en'];
	const template = selected[key] ?? messages.en[key] ?? key;
	return template.replace(/\{([a-zA-Z]+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
}

